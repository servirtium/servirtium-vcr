#!/bin/sh
# Regenerate core/bru_js.ae: the vendored Bruno parser's JavaScript (and the
# glue) as Aether heredoc strings, so the converter carries them in its
# binary and needs no files at run time. Run after changing anything under
# core/bru/third_party/ or core/bru/glue.js:
#
#     sh core/bru/gen.sh            # write core/bru_js.ae
#     sh core/bru/gen.sh --check    # exit 1 if core/bru_js.ae is stale
#
# The files go in byte for byte (a heredoc has no escapes and no ${}). The
# check mode is part of core_tests (test_vcr_bru_upstream), so an edit to a
# vendored file that is not regenerated fails the tests.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
core=$(dirname "$here")

marker=SVCR_BRU_JS_END

# name (as require() sees it) and file, one pair per line. The runtime set:
# what bruToJson, collectionBruToJson and envToJson reach, and nothing else
# (Bruno's serialisers and tests stay on disk for the drift test only).
modules="
ohm-js third_party/ohm-js-16.6.0/dist/ohm.cjs
lodash third_party/lodash-4.18.1/lodash.min.js
v2/src/utils third_party/usebruno-lang-0.41.0/v2/src/utils.js
v2/src/common/attributes third_party/usebruno-lang-0.41.0/v2/src/common/attributes.js
v2/src/common/semantic-utils third_party/usebruno-lang-0.41.0/v2/src/common/semantic-utils.js
v2/src/example/request/bruToJson third_party/usebruno-lang-0.41.0/v2/src/example/request/bruToJson.js
v2/src/example/response/bruToJson third_party/usebruno-lang-0.41.0/v2/src/example/response/bruToJson.js
v2/src/example/bruToJson third_party/usebruno-lang-0.41.0/v2/src/example/bruToJson.js
v2/src/bruToJson third_party/usebruno-lang-0.41.0/v2/src/bruToJson.js
v2/src/collectionBruToJson third_party/usebruno-lang-0.41.0/v2/src/collectionBruToJson.js
v2/src/envToJson third_party/usebruno-lang-0.41.0/v2/src/envToJson.js
"

emit() {
    printf '%s\n' "// GENERATED by core/bru/gen.sh from core/bru/glue.js and core/bru/third_party/"
    printf '%s\n' "// (see core/bru/PROVENANCE.md). Do not edit: change those and rerun it."
    printf '%s\n' "// Each function returns one file's text verbatim, as a heredoc."
    printf '\n'
    printf '%s\n' "exports (bru_js_glue, bru_js_module_count, bru_js_module_name, bru_js_module_source)"
    printf '\n'
    printf '%s\n' "bru_js_glue() -> string {"
    printf '%s\n' "    return <<$marker"
    cat "$here/glue.js"
    printf '%s\n' "$marker"
    printf '%s\n' "}"
    n=0
    names=""
    echo "$modules" | while read -r name file; do
        [ -z "$name" ] && continue
        if grep -qx "[[:space:]]*$marker" "$here/$file"; then
            echo "gen.sh: $file holds a line '$marker'" >&2
            exit 1
        fi
        printf '\n%s\n' "fn bru_js_src_$n() -> string {"
        printf '%s\n' "    return <<$marker"
        cat "$here/$file"
        # a heredoc drops the newline before its marker; keep the file's own
        printf '\n%s\n' "$marker"
        printf '%s\n' "}"
        n=$((n + 1))
    done
    count=$(echo "$modules" | grep -c .)
    printf '\n%s\n' "bru_js_module_count() -> int { return $count }"
    printf '\n%s\n' "bru_js_module_name(i: int) -> string {"
    i=0
    echo "$modules" | while read -r name file; do
        [ -z "$name" ] && continue
        printf '%s\n' "    if i == $i { return \"$name\" }"
        i=$((i + 1))
    done
    printf '%s\n' "    return \"\""
    printf '%s\n' "}"
    printf '\n%s\n' "bru_js_module_source(i: int) -> string {"
    i=0
    echo "$modules" | while read -r name file; do
        [ -z "$name" ] && continue
        printf '%s\n' "    if i == $i { return bru_js_src_$i() }"
        i=$((i + 1))
    done
    printf '%s\n' "    return \"\""
    printf '%s\n' "}"
}

if [ "${1:-}" = "--check" ]; then
    tmp=$(mktemp)
    emit > "$tmp"
    if cmp -s "$tmp" "$core/bru_js.ae"; then rm -f "$tmp"; echo "gen.sh: core/bru_js.ae is current"; exit 0; fi
    rm -f "$tmp"
    echo "gen.sh: core/bru_js.ae is stale: run sh core/bru/gen.sh" >&2
    exit 1
fi
emit > "$core/bru_js.ae"
echo "gen.sh: wrote core/bru_js.ae"
