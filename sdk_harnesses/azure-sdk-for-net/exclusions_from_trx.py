#!/usr/bin/env python3
"""Write excluded.txt from a `run.sh direct` result (a TRX file).

A maintenance tool, not part of a run (the harness itself needs only .NET):
`run.sh direct` runs the selected tests against Azurite with no Servirtium,
and every test that fails there is excluded, grouped by how it failed, so
the reason in excluded.txt is what Azurite did, not a guess. Tests that pass
directly but fail through Servirtium are Servirtium's to fix, never excluded.

    python3 -I exclusions_from_trx.py target/results/direct/*.trx \
        --oversized target/work/record/oversized.txt > excluded.txt
"""
import collections
import re
import sys
import xml.etree.ElementTree as ET

NS = "{http://microsoft.com/schemas/VisualStudio/TeamTest/2010}"

# Failure text -> the reason written in excluded.txt. First match wins.
KNOWN = [
    (r"Cannot use client-provided key without HTTPS", "customer-provided keys need HTTPS, and the harness talks HTTP to Azurite"),
    (r"ErrorCode: (\w+)", "Azurite answers {0} where Azure succeeds"),
    (r"Value cannot be null\. \(Parameter 'uriString'\)", "needs an endpoint or tenant only an Azure account has (secondary, OAuth or premium tenant)"),
    (r"Root element is missing", "Azurite's listing of encoded blob names is not what the SDK parses"),
    (r"Expected: (High|Standard)", "Azurite does not report rehydrate priority"),
    (r"Status: 400 \(Bad Request\)", "Azurite does not support the request (400)"),
    (r"Status: 501", "Azurite does not implement the operation (501)"),
    (r"Expected exception not found", "Azurite accepts what Azure refuses"),
]


def reason_for(msg):
    for pattern, reason in KNOWN:
        m = re.search(pattern, msg)
        if m:
            return reason.format(*m.groups())
    exp = re.search(r"Expected: (.*)", msg)
    was = re.search(r"But was:\s+(.*)", msg)
    if exp and was:
        return "Azurite answers differently: the test expected %s, got %s" % (exp.group(1).strip()[:60], was.group(1).strip()[:60])
    first = msg.strip().split("\n")[0]
    first = re.sub(r"[0-9a-f]{8}-[0-9a-f-]{27}", "GUID", first)
    return "fails against Azurite itself: " + first[:150]


def main(args):
    groups = collections.defaultdict(set)
    paths = []
    while args:
        a = args.pop(0)
        if a == "--oversized":
            # run.sh record's target/work/record/oversized.txt: tests that
            # pass through Servirtium but whose tape is over the size cap.
            for line in open(args.pop(0), encoding="utf-8"):
                name = line.split("\t")[0].strip()
                if name:
                    groups["its tape is over the 128 KiB cap (bulk upload or download data): passes through Servirtium, not checked in"].add(name)
        else:
            paths.append(a)
    for path in paths:
        root = ET.parse(path).getroot()
        names = {}
        for ut in root.iter(NS + "UnitTest"):
            cls = re.sub(r"\(.*\)$", "", ut.find(NS + "TestMethod").get("className")).split(".")[-1]
            names[ut.get("id")] = cls + "." + ut.get("name")
        for res in root.iter(NS + "UnitTestResult"):
            if res.get("outcome") != "Failed":
                continue
            m = res.find(".//" + NS + "Message")
            groups[reason_for(m.text or "" if m is not None else "")].add(names[res.get("testId")])
    print("# Generated by exclusions_from_trx.py from `run.sh direct` (Azurite, no")
    print("# Servirtium). Each test below fails against Azurite itself.")
    for reason in sorted(groups):
        print()
        print("## " + reason)
        for name in sorted(groups[reason]):
            print(name)


if __name__ == "__main__":
    main(sys.argv[1:])
